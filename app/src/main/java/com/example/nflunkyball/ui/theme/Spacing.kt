package com.example.nflunkyball.ui.theme

import androidx.compose.ui.unit.dp

/** A single consistent spacing scale, replacing the ad-hoc 4/8/12/16/20/24dp literals scattered
 *  across individual screens — use these instead of a new magic-number `.dp` value. */
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp
}
